"""The rungs below the model.

The question this file answers: *does a language model need to read this invoice
at all?*

Often, no. A PDF generated by a carrier's billing system carries a text layer, and
a text layer with its spatial layout preserved puts every charge description on the
same line as its amount. That is not a language problem. It is a parsing problem,
and parsing is free, instant, and deterministic.

So the extraction path is a **ladder**, and each rung is tried only when the one
below it fails:

    1  pdfplumber layout parse      free      deterministic, ~0 ms
    2  arithmetic validation        free      the parse must reconcile
    3  vision model                 ~$0.07    only when 1 or 2 fail

**What the investigation actually found**, measured on these invoices rather than
assumed:

  - **MarkItDown** (Microsoft's `markitdown`, which wraps `pdfminer.six`) returns
    all the text including every amount, but in *reading order*: right-aligned
    figures land in a separate run at the end of the document, decoupled from the
    descriptions they belong to. Excellent for deciding *what a document is*.
    Unusable for deciding *what it says*, because the association is gone.
  - **pdfplumber with `layout=True`** preserves the spatial arrangement, so
    `Linehaul transportation charge ... $856.06` stays on one line. That is
    parseable, and this module parses it.

**Why the model still exists.** Three reasons, and they are the honest limits of
this approach:

  1. **Scanned invoices have no text layer at all.** Plenty of carriers still send
     images. The ladder detects that in stage 1 and falls straight to vision.
  2. **Layout parsing is per-carrier.** This parser is written against one
     carrier's template. The next carrier's invoice will not match it, and writing
     a parser per carrier is exactly the maintenance burden that made everyone
     reach for models in the first place. The model generalises; the parser does
     not.
  3. **The arithmetic gate is what makes the cheap rung safe.** A regex parser that
     silently mis-associates an amount is far more dangerous than a model that
     misreads one, because it fails with total confidence. The sum check is what
     makes it acceptable to trust the free path: if the parse does not reconcile to
     the printed totals, the document goes to the model instead.

Net effect: the model is reached for the documents that need it, and the cost of a
run falls by roughly the cost of extraction on every invoice that has a clean text
layer.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from datetime import date
from pathlib import Path

from .schema import ExtractedCharge, ExtractedInvoice, ExtractedInvoiceLine

MIN_TEXT_CHARS = 400          # below this, treat the PDF as a scan with no text layer

# Freight vocabulary. Used only for the free triage gate, never for extraction.
FREIGHT_TERMS = (
    "pro number", "bill of lading", "bol", "linehaul", "line haul", "fuel surcharge",
    "freight", "carrier", "shipment", "accessorial", "liftgate", "lift gate",
    "detention", "consignee", "shipper", "tariff", "class", "cwt", "hundredweight",
    "nmfc", "pickup", "delivery receipt", "reweigh",
)
INVOICE_TERMS = ("invoice", "total due", "amount due", "remit", "terms:", "bill to")

PRO_RE = re.compile(r"\b[A-Z]{2,4}\d{7,12}\b")
MONEY_RE = re.compile(r"\$\s?([\d,]+\.\d{2})")

# One shipment header line, with weight and class embedded as free text.
HEADER_RE = re.compile(
    r"(?P<pro>[A-Z]{2,4}\d{7,12})\s+BOL\s+(?P<bol>\S+)\s+Shipped\s+"
    r"(?P<date>\d{4}-\d{2}-\d{2})\s+(?P<orig>\S+)\s+to\s+(?P<dest>\S+)\s+"
    r"Billed\s+Wt\s+(?P<wt>[\d,]+)\s*lb\s+Class\s+(?P<cls>[\d.]+)"
)
CHARGE_RE = re.compile(r"^\s+(?P<desc>\S.*?)\s{2,}\$\s?(?P<amt>[\d,]+\.\d{2})\s*$")

DESC_TO_CODE = {
    "linehaul": "LINEHAUL",
    "fuel surcharge": "FUEL_SURCHARGE",
    "liftgate": "LIFTGATE_DELIVERY",
    "residential": "RESIDENTIAL_DELIVERY",
    "inside delivery": "INSIDE_DELIVERY",
    "limited access": "LIMITED_ACCESS",
    "appointment": "APPOINTMENT",
    "detention": "DETENTION",
    "reweigh": "REWEIGH_FEE",
    "reclassification": "RECLASSIFICATION_FEE",
    "redelivery": "REDELIVERY",
    "lumper": "LUMPER",
}


def _code_for(description: str) -> str:
    d = description.lower()
    for needle, code in DESC_TO_CODE.items():
        if needle in d:
            return code
    return "OTHER"


def _money(s: str) -> float:
    return float(s.replace(",", ""))


# --------------------------------------------------------------------------
# Stage 1 -- get the text, with layout
# --------------------------------------------------------------------------


def extract_text(path: Path) -> str:
    """Layout-preserving text. Returns '' when the PDF has no text layer."""
    try:
        import pdfplumber
    except ImportError:
        return ""
    try:
        with pdfplumber.open(str(path)) as pdf:
            return "\n".join((p.extract_text(layout=True) or "") for p in pdf.pages)
    except Exception:
        return ""


def has_text_layer(text: str) -> bool:
    return len(text.strip()) >= MIN_TEXT_CHARS


# --------------------------------------------------------------------------
# Free triage -- replaces a model call
# --------------------------------------------------------------------------


@dataclass
class TriageVerdict:
    is_freight_invoice: bool
    confident: bool
    document_kind: str
    reason: str
    freight_hits: int
    invoice_hits: int
    pro_numbers: int


def triage_text(text: str) -> TriageVerdict:
    """Decide whether a document is a carrier freight invoice, for free.

    Three independent signals, all cheap: freight vocabulary, invoice vocabulary,
    and PRO-number-shaped tokens. The verdict is only reported as `confident` when
    the signals agree strongly; an ambiguous document is handed to the model, which
    is the expensive answer for the small number of cases that need it.

    This is the rung below the cheap model call, and it removes that call entirely
    for every document that is obviously an invoice or obviously not one.
    """
    low = text.lower()
    freight = sum(1 for t in FREIGHT_TERMS if t in low)
    invoice = sum(1 for t in INVOICE_TERMS if t in low)
    pros = len(set(PRO_RE.findall(text)))

    if freight >= 5 and invoice >= 2 and pros >= 1:
        return TriageVerdict(
            True, True, "carrier freight invoice",
            f"{freight} freight terms, {invoice} invoice terms and {pros} PRO-shaped "
            f"identifiers. Unambiguous.", freight, invoice, pros)

    if freight <= 1 and pros == 0:
        kind = "an invoice or statement, but not for freight" if invoice >= 1 else "not an invoice"
        return TriageVerdict(
            False, True, kind,
            f"Only {freight} freight terms and no PRO numbers. Whatever this is, it is "
            f"not a carrier billing for transportation.", freight, invoice, pros)

    return TriageVerdict(
        False, False, "unclear",
        f"Mixed signals: {freight} freight terms, {invoice} invoice terms, {pros} PRO "
        f"numbers. Too ambiguous to decide for free.", freight, invoice, pros)


# --------------------------------------------------------------------------
# Deterministic parse
# --------------------------------------------------------------------------


def parse_invoice(text: str) -> ExtractedInvoice | None:
    """Parse this carrier's layout into the same schema the model produces.

    Returns None the moment anything does not fit, rather than guessing. The caller
    treats None as "use the model" -- a parser that returns a half-right answer is
    worse than one that declines, because the arithmetic downstream would validate
    against numbers it also got wrong.

    Note what is NOT done here: no amount is computed, adjusted or inferred. Values
    are transcribed exactly as printed, identically to the model's contract, so the
    sum check that follows is a real test of both paths.
    """
    m_inv = re.search(r"Invoice\s+(MFS-INV-\S+)", text)
    m_date = re.search(r"Invoice Date\s+(\d{4}-\d{2}-\d{2})", text)
    m_total = re.search(r"TOTAL DUE\s+\$\s?([\d,]+\.\d{2})", text)
    if not (m_inv and m_total):
        return None

    # Layout mode keeps the letterhead and the "FREIGHT INVOICE" banner on the same
    # visual line, separated by a wide run of spaces, and preserves the letter-spacing
    # inside the name itself. Cut at the column gap and collapse the internal runs, so
    # the carrier name is the name rather than the whole top line of the page. This is
    # still transcription -- no character is added, only layout whitespace removed.
    first = text.strip().splitlines()[0].strip() if text.strip() else ""
    carrier = re.sub(r"\s{2,}", " ", re.split(r"\s{6,}", first)[0]).strip()
    if not carrier:
        return None

    lines: list[ExtractedInvoiceLine] = []
    current: dict | None = None
    charges: list[ExtractedCharge] = []

    for raw in text.splitlines():
        h = HEADER_RE.search(raw)
        if h:
            if current is not None:
                return None          # a header before the previous line was closed
            current = h.groupdict()
            charges = []
            continue

        if current is None:
            continue

        c = CHARGE_RE.match(raw)
        if not c:
            continue

        desc, amt = c.group("desc").strip(), _money(c.group("amt"))
        if desc.lower().startswith("shipment total"):
            lines.append(ExtractedInvoiceLine(
                pro_number=current["pro"], bol_number=current["bol"],
                ship_date=date.fromisoformat(current["date"]),
                origin_zip=current["orig"], dest_zip=current["dest"],
                billed_weight_lb=_money(current["wt"]),
                billed_class=float(current["cls"]),
                charges=charges, line_total=amt,
            ))
            current, charges = None, []
        else:
            charges.append(ExtractedCharge(
                code=_code_for(desc), description=desc, amount=amt))

    if current is not None or not lines:
        return None

    return ExtractedInvoice(
        carrier_name=carrier,
        invoice_number=m_inv.group(1),
        invoice_date=date.fromisoformat(m_date.group(1)) if m_date else None,
        lines=lines,
        invoice_total=_money(m_total.group(1)),
    )
